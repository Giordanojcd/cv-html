function setupRevealObserver() {
    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                entry.target.classList.add("is-visible");
                observer.unobserve(entry.target);
            }
        });
    }, { threshold: 0.12 });

    document.querySelectorAll(".reveal").forEach((section) => observer.observe(section));
}

function setupSectionObserver() {
    const navMap = new Map(Array.from(elements.navLinks).map((link) => [link.dataset.nav, link]));
    const ids = ["experience", "education", "certifications", "skills", "contact"];
    const sections = ids.map((id) => document.getElementById(id)).filter(Boolean);

    const observer = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
            if (entry.isIntersecting) {
                elements.navLinks.forEach((link) => link.classList.remove("active"));
                const link = navMap.get(entry.target.id);
                if (link) {
                    link.classList.add("active");
                }
            }
        });
    }, { rootMargin: "-35% 0px -45% 0px", threshold: 0.01 });

    sections.forEach((section) => observer.observe(section));
}

function setupScrollEffects() {
    const floatingItems = [
        { element: elements.ambientA, speed: -0.08 },
        { element: elements.ambientB, speed: 0.12 },
        { element: elements.heroCard, speed: 0.03 },
        { element: elements.heroPanel, speed: 0.05 }
    ].filter((item) => item.element);

    floatingItems.forEach((item) => item.element.classList.add("scroll-float"));

    let ticking = false;

    function updateOnScroll() {
        const y = window.scrollY;

        if (elements.topbar) {
            elements.topbar.classList.toggle("is-scrolled", y > 24);
        }

        floatingItems.forEach(({ element, speed }) => {
            const offset = Math.min(y * speed, 32);
            element.style.transform = `translate3d(0, ${offset}px, 0)`;
        });

        ticking = false;
    }

    function requestTick() {
        if (!ticking) {
            window.requestAnimationFrame(updateOnScroll);
            ticking = true;
        }
    }

    window.addEventListener("scroll", requestTick, { passive: true });
    updateOnScroll();
}

function setupContactTilt() {
    const card = elements.contactTilt;
    if (!card || window.matchMedia("(pointer: coarse)").matches) {
        return;
    }

    card.addEventListener("mousemove", (event) => {
        const bounds = card.getBoundingClientRect();
        const offsetX = (event.clientX - bounds.left) / bounds.width;
        const offsetY = (event.clientY - bounds.top) / bounds.height;
        const rotateY = (offsetX - 0.5) * 8;
        const rotateX = (0.5 - offsetY) * 8;

        card.style.transform = `perspective(1200px) rotateX(${rotateX}deg) rotateY(${rotateY}deg) translateY(-3px)`;
    });

    card.addEventListener("mouseleave", () => {
        card.style.transform = "";
    });
}

