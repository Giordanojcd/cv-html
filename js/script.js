function renderTechChip(label, fallbackIcon = "fa-layer-group") {
    const asset = techIconMap[label];
    const brandColor = techBrandColors[label] || "var(--accent)";
    let media = `<i class="fa-solid ${fallbackIcon}"></i>`;

    if (typeof asset === "string") {
        media = `<img src="${asset}" alt="${label} logo" loading="lazy" referrerpolicy="no-referrer">`;
    } else if (asset?.iconClass) {
        media = `<i class="${asset.iconClass}"></i>`;
    }

    return `
        <span class="chip chip-with-icon" style="--chip-brand:${brandColor}">
            <span class="chip-icon">${media}</span>
            <span>${label}</span>
        </span>
    `;
}

